# 1. HELMET MODEL — best.pt
# ══════════════════════════════════════════════════════════

print("\n" + "─" * 65)
print("  [1/2] HELMET MODEL — models/best.pt")
print("─" * 65)

helmet_data = {}

HELMET_MODEL   = "models/best.pt"
HELMET_DATASET = "datasets/helmet_lc.v3i.yolov8/data.yaml"

if not os.path.exists(HELMET_MODEL):
    print(f"❌ Not found: {HELMET_MODEL}")
elif not os.path.exists(HELMET_DATASET):
    print(f"❌ Dataset not found: {HELMET_DATASET}")
else:
    m = YOLO(HELMET_MODEL)
    print(f"✅ Loaded | Classes: {m.names}")
    print("Running val() on test split...")

    t0 = time.time()
    res = m.val(
        data=HELMET_DATASET, split="test",
        imgsz=640, conf=0.25, iou=0.5,
        verbose=False, project=OUTPUT_DIR,
        name="helmet_eval", exist_ok=True
    )
    elapsed = time.time() - t0

    mp    = float(res.box.mp)
    mr    = float(res.box.mr)
    map50 = float(res.box.map50)
    map_  = float(res.box.map)

    print(f"\n  Mean Precision : {mp*100:.1f}%")
    print(f"  Mean Recall    : {mr*100:.1f}%")
    print(f"  mAP@0.5        : {map50*100:.1f}%")
    print(f"  mAP@0.5:0.95   : {map_*100:.1f}%")
    print(f"  Time           : {elapsed:.1f}s")

    per_class = {}
    if hasattr(res.box, 'ap_class_index'):
        print(f"\n  {'Class':<16} {'Precision':>10} {'Recall':>8} {'mAP@0.5':>9}")
        print("  " + "─" * 46)
        for idx, cid in enumerate(res.box.ap_class_index):
            name = m.names[int(cid)]
            p    = float(res.box.p[idx])    if res.box.p    is not None else 0
            r    = float(res.box.r[idx])    if res.box.r    is not None else 0
            ap50 = float(res.box.ap50[idx]) if res.box.ap50 is not None else 0
            per_class[name] = {"precision": round(p,4), "recall": round(r,4), "ap50": round(ap50,4)}
            print(f"  {name:<16} {p*100:>9.1f}% {r*100:>7.1f}% {ap50*100:>8.1f}%")

    # Confusion matrix path (generated by YOLO val)
    cm_path = os.path.join(OUTPUT_DIR, "helmet_eval", "confusion_matrix_normalized.png")
    if os.path.exists(cm_path):
        print(f"\n  Confusion matrix: {cm_path}")
    else:
        print(f"\n  ⚠️  Confusion matrix not found at expected path")

    print("\n  ── Analysis ──")
    print(f"  • helmet recall {per_class.get('helmet',{}).get('recall',0)*100:.1f}% — catches most helmeted riders")
    print(f"  • nohelmet precision {per_class.get('nohelmet',{}).get('precision',0)*100:.1f}% on test set (false positives observed on out-of-distribution images)")
    print(f"  • nohelmet recall {per_class.get('nohelmet',{}).get('recall',0)*100:.1f}% — 20-frame voting compensates in live pipeline")
    print(f"  • licenseplate class is weak ({per_class.get('licenseplate',{}).get('ap50',0)*100:.1f}% mAP) — Plate.pt used instead")

    helmet_data = {
        "model": HELMET_MODEL, "dataset": HELMET_DATASET,
        "mean_precision": round(mp,4), "mean_recall": round(mr,4),
        "map50": round(map50,4), "map50_95": round(map_,4),
        "per_class": per_class, "eval_time_s": round(elapsed,2),
        "confusion_matrix": cm_path if os.path.exists(cm_path) else "not found",
    }
    with open(os.path.join(OUTPUT_DIR, "metrics_helmet.json"), "w") as f:
        json.dump(helmet_data, f, indent=2)
    print(f"\n✅ Saved: results/model_eval/metrics_helmet.json")


