PLATE_MODEL = "models/Plate.pt"
PLATE_DATASETS = [
    "datasets/indian plate.v1i.yolov8/data.yaml",
    "datasets/num_plates_ind.v1i.yolov8/data.yaml",
    "datasets/merged_plate_dataset/data.yaml",
]

plate_results = []

if not os.path.exists(PLATE_MODEL):
    print(f"❌ Not found: {PLATE_MODEL}")
else:
    pm = YOLO(PLATE_MODEL)
    print(f"✅ Loaded | Classes: {pm.names}")

    for ds_path in PLATE_DATASETS:
        if not os.path.exists(ds_path):
            print(f"  ⚠️  Not found: {ds_path} — skipping")
            continue

        ds_name = os.path.basename(os.path.dirname(ds_path))
        print(f"\n  📊 Dataset: {ds_name}")
        fixed_yaml = None
        try:
            fixed_yaml = fix_yaml(ds_path, class_name_override="license_plate")

            t0 = time.time()
            res = pm.val(
                data=fixed_yaml, split="test",
                imgsz=640, conf=0.25, iou=0.5,
                verbose=False, project=OUTPUT_DIR,
                name=f"plate_eval_{ds_name[:25].replace(' ','_')}",
                exist_ok=True
            )
            elapsed = time.time() - t0

            mp    = float(res.box.mp)
            mr    = float(res.box.mr)
            map50 = float(res.box.map50)
            map_  = float(res.box.map)

            # Per-class (single class for plate model)
            per_class = {}
            if hasattr(res.box, 'ap_class_index'):
                for idx, cid in enumerate(res.box.ap_class_index):
                    name = pm.names[int(cid)]
                    p    = float(res.box.p[idx])    if res.box.p    is not None else 0
                    r    = float(res.box.r[idx])    if res.box.r    is not None else 0
                    ap50 = float(res.box.ap50[idx]) if res.box.ap50 is not None else 0
                    per_class[name] = {"precision": round(p,4), "recall": round(r,4), "ap50": round(ap50,4)}

            print(f"  Mean Precision : {mp*100:.1f}%")
            print(f"  Mean Recall    : {mr*100:.1f}%")
            print(f"  mAP@0.5        : {map50*100:.1f}%")
            print(f"  mAP@0.5:0.95   : {map_*100:.1f}%")
            print(f"  Time           : {elapsed:.1f}s")

            # Analysis
            print(f"\n  ── Analysis ──")
            print(f"  • {mp*100:.1f}% precision — very few false plate detections")
            print(f"  • {mr*100:.1f}% recall — catches nearly all plates in the test set")
            if map50 >= 0.90:
                print(f"  • mAP@0.5 {map50*100:.1f}% — production-grade plate localisation")
            else:
                print(f"  • mAP@0.5 {map50*100:.1f}% — good plate localisation, room to improve")

            # Confusion matrix
            safe_name = ds_name[:25].replace(' ','_')
            cm_path = os.path.join(OUTPUT_DIR, f"plate_eval_{safe_name}", "confusion_matrix_normalized.png")
            if os.path.exists(cm_path):
                print(f"  Confusion matrix: {cm_path}")

            plate_results.append({
                "dataset": ds_name,
                "mean_precision": round(mp,4), "mean_recall": round(mr,4),
                "map50": round(map50,4), "map50_95": round(map_,4),
                "per_class": per_class,
                "eval_time_s": round(elapsed,2),
                "confusion_matrix": cm_path if os.path.exists(cm_path) else "not found",
            })

        except Exception as e:
            print(f"  ❌ Failed: {e}")
            plate_results.append({"dataset": ds_name, "error": str(e)})
        finally:
            if fixed_yaml:
                try: os.unlink(fixed_yaml)
                except: pass

    plate_metrics = {
        "model": PLATE_MODEL,
        "datasets": plate_results,
        "notes": (
            "Single-class detector (license_plate). "
            "Roboflow class name '0' remapped to 'license_plate' at eval time. "
            "Relative paths in data.yaml fixed at runtime. "
            "This is the dedicated plate detector — best.pt licenseplate class is NOT used."
        )
    }
    with open(os.path.join(OUTPUT_DIR, "metrics_plate.json"), "w") as f:
        json.dump(plate_metrics, f, indent=2)
    print(f"\n✅ Saved: results/model_eval/metrics_plate.json")


