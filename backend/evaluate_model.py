# HELPER — fix Roboflow data.yaml paths
# ══════════════════════════════════════════════════════════

def fix_yaml(yaml_path, class_name_override=None):
    """
    Roboflow yamls use paths like ../train/images (relative, going UP).
    This is wrong when running from project root — the images are INSIDE
    the dataset folder, not above it.

    Correct mapping:
      ../train/images  →  {dataset_dir}/train/images
      ../valid/images  →  {dataset_dir}/valid/images
      ../test/images   →  {dataset_dir}/test/images
    """
    import yaml

    dataset_dir = os.path.dirname(os.path.abspath(yaml_path))

    with open(yaml_path, 'r') as f:
        data = yaml.safe_load(f)

    for key in ['train', 'val', 'test']:
        if key not in data or not data[key]:
            continue
        p = str(data[key])
        if os.path.isabs(p) and os.path.exists(p):
            continue  # already absolute and exists — keep it

        # Strip leading ../ or ./ and resolve INSIDE the dataset folder
        # e.g. ../train/images → train/images → {dataset_dir}/train/images
        stripped = p.lstrip('.').lstrip('/').lstrip('\\')
        candidate = os.path.join(dataset_dir, stripped)
        if os.path.exists(candidate):
            data[key] = candidate
        else:
            # fallback: standard normpath resolution
            data[key] = os.path.normpath(os.path.join(dataset_dir, p))

    if class_name_override:
        data['names'] = [class_name_override]

    tmp = tempfile.NamedTemporaryFile(mode='w', suffix='.yaml', delete=False)
    import yaml as y2
    y2.dump(data, tmp)
    tmp.close()
    return tmp.name


